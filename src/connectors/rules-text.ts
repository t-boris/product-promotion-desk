// Heuristic reading of community rules for automation and promotion restrictions. It only ever makes
// the system more cautious: a match restricts sending, and the quoted rule is shown to the owner.

export interface RuleText {
  name: string
  text: string
}

export interface RulesAnalysis {
  /** First rule that appears to forbid bots, automation or AI-generated content. */
  automationForbidden: RuleText | null
  /** Rules that mention self-promotion, advertising or similar. Shown as a warning, never as a block. */
  promotionRules: RuleText[]
}

const AUTOMATION_TERM = /\b(bots?|automat(?:ed|ion|ically)|auto-?post(?:ing|ed)?|ai[- ]generated|ai[- ]written|generated by (?:an? )?ai|chat-?gpt|llms?|artificial intelligence)\b/gi
const PROHIBITION_CUE = /\b(no|not|never|ban(?:ned)?|prohibit(?:ed)?|forbid(?:den)?|disallow(?:ed)?|don'?t|do not|must not|mustn'?t|isn'?t allowed|aren'?t allowed|against the rules|will be removed|are removed|permanently)\b/i
const PERMISSION_CUE = /\b(allowed (?:only )?(?:if|when|for)|welcome|permitted (?:if|when))\b/i
const PROMOTION_TERM = /\b(self[- ]?promo(?:tion|tional)?|advertis(?:e|es|ing|ement|ements)|promot(?:e|es|ing|ion|ional)|spam|marketing|affiliate|referral)\b/i

const WINDOW = 90

function forbidsAutomation(text: string): boolean {
  for (const match of text.matchAll(AUTOMATION_TERM)) {
    const start = Math.max(0, (match.index ?? 0) - WINDOW)
    const around = text.slice(start, (match.index ?? 0) + match[0].length + WINDOW)
    if (PROHIBITION_CUE.test(around) && !PERMISSION_CUE.test(around)) return true
  }
  return false
}

export function analyzeRules(rules: RuleText[]): RulesAnalysis {
  let automationForbidden: RuleText | null = null
  const promotionRules: RuleText[] = []
  for (const rule of rules) {
    const full = `${rule.name}. ${rule.text}`
    if (!automationForbidden && forbidsAutomation(full)) automationForbidden = rule
    if (PROMOTION_TERM.test(full)) promotionRules.push(rule)
  }
  return { automationForbidden, promotionRules }
}

/** One-line quotation of a rule for capability details. */
export function quoteRule(rule: RuleText, max = 140): string {
  const text = rule.text.replace(/\s+/g, ' ').trim()
  const body = text.length > max ? `${text.slice(0, max - 1)}…` : text
  return body ? `"${rule.name}": ${body}` : `"${rule.name}"`
}
