#!/usr/bin/env python3
"""Makes the menu-bar icon from the application icon (build/icon.png) and writes src/main/tray-icon.ts.

macOS wants a "template" image there: black on transparent, which the system recolours for a light or a dark menu bar. The glyph is the white
speech bubble of the application icon with its check mark cut out. Run `python3 scripts/make-tray-icon.py` (needs Pillow) after the icon changes.
"""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZES = {"1x": 18, "2x": 36}
SUPERSAMPLE = 8


def glyph(source: Image.Image) -> Image.Image:
    rgba = source.convert("RGBA")
    px = rgba.load()
    w, h = rgba.size
    mask = Image.new("L", (w, h), 0)
    out = mask.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255
            # the bubble is white; the check mark, the background and the shadow are darker
            out[x, y] = int(255 * max(0.0, min(1.0, (lum - 0.82) / 0.12)) * (a / 255))
    box = mask.getbbox()
    cropped = mask.crop(box)
    side = max(cropped.size)
    square = Image.new("L", (side, side), 0)
    square.paste(cropped, ((side - cropped.width) // 2, (side - cropped.height) // 2))
    return square


def template(mask: Image.Image, size: int, margin: float) -> bytes:
    inner = round(size * (1 - 2 * margin))
    big = mask.resize((inner * SUPERSAMPLE, inner * SUPERSAMPLE), Image.LANCZOS).resize((inner, inner), Image.LANCZOS)
    canvas = Image.new("L", (size, size), 0)
    canvas.paste(big, ((size - inner) // 2, (size - inner) // 2))
    image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    image.putalpha(canvas)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def main() -> None:
    mask = glyph(Image.open(ROOT / "build" / "icon.png"))
    encoded = {name: base64.b64encode(template(mask, size, 0.06)).decode() for name, size in SIZES.items()}
    (ROOT / "src" / "main" / "tray-icon.ts").write_text(
        "// GENERATED by scripts/make-tray-icon.py from build/icon.png: do not edit by hand.\n"
        "// The menu-bar icon: the speech bubble of the application icon, black on transparent, as a macOS template image (18 pt, with a 36 px version for Retina).\n\n"
        f"export const TRAY_ICON_1X = '{encoded['1x']}'\n"
        f"export const TRAY_ICON_2X = '{encoded['2x']}'\n"
    )


main()
